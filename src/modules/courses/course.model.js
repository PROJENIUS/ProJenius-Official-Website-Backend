import mongoose from "mongoose";

const courseSchema = new mongoose.Schema({
  title: { type: String, required: true, trim: true, maxlength: 180 },
  slug: { type: String, required: true, trim: true, lowercase: true, maxlength: 190 },
  shortDescription: { type: String, required: true, trim: true, maxlength: 360 },
  description: { type: String, required: true, trim: true, maxlength: 15000 },
  category: { type: String, required: true, trim: true, maxlength: 100 },
  language: { type: String, trim: true, maxlength: 80, default: "" },
  level: { type: String, enum: ["", "beginner", "intermediate", "advanced"], default: "" },
  coverImage: {
    mediaId: { type: mongoose.Schema.Types.ObjectId, default: null },
    filename: { type: String, default: null },
    originalFilename: { type: String, trim: true, maxlength: 255, default: "" },
    mimeType: { type: String, default: null },
    size: { type: Number, default: null },
    uploadedAt: { type: Date, default: null },
    alt: { type: String, trim: true, maxlength: 180, default: "" },
  },
  learningOutcomes: { type: [String], default: [] },
  curriculum: [{ title: { type: String, required: true, trim: true, maxlength: 180 }, description: { type: String, trim: true, maxlength: 1000, default: "" }, duration: { type: String, trim: true, maxlength: 80, default: "" }, lessons: [{ title: { type: String, trim: true, maxlength: 180, required: true }, summary: { type: String, trim: true, maxlength: 800, default: "" }, type: { type: String, enum: ["reading", "recorded-reference", "practical", "quiz"], default: "reading" }, duration: { type: String, trim: true, maxlength: 80, default: "" }, resourceUrl: { type: String, trim: true, maxlength: 1000, default: "" } }] }],
  skills: { type: [String], default: [] },
  tools: { type: [String], default: [] },
  projects: [{ title: { type: String, trim: true, maxlength: 160, required: true }, description: { type: String, trim: true, maxlength: 1200, default: "" }, technologies: { type: [String], default: [] }, outcome: { type: String, trim: true, maxlength: 500, default: "" }, order: { type: Number, default: 0 } }],
  certificate: { available: { type: Boolean, default: false }, description: { type: String, trim: true, maxlength: 800, default: "" } },
  faqs: [{ question: { type: String, trim: true, maxlength: 300, required: true }, answer: { type: String, trim: true, maxlength: 1500, required: true }, order: { type: Number, default: 0 } }],
  duration: { type: String, required: true, trim: true, maxlength: 100 },
  deliveryMode: { type: String, enum: ["online", "in-person", "hybrid", "self-paced"], required: true },
  audience: { type: String, trim: true, maxlength: 1000, default: "" },
  prerequisites: { type: String, trim: true, maxlength: 2000, default: "" },
  instructor: { name: { type: String, trim: true, maxlength: 120, default: "" }, designation: { type: String, trim: true, maxlength: 120, default: "" }, bio: { type: String, trim: true, maxlength: 2000, default: "" }, expertise: { type: [String], default: [] }, profileUrl: { type: String, trim: true, maxlength: 500, default: "" } },
  deliveryDetails: {
    onlinePlatform: { type: String, trim: true, maxlength: 80, default: "" },
    onlineJoinUrl: { type: String, trim: true, maxlength: 1000, default: "" },
    onlineAccessCode: { type: String, trim: true, maxlength: 200, default: "" },
    venueName: { type: String, trim: true, maxlength: 180, default: "" },
    venueAddress: { type: String, trim: true, maxlength: 1000, default: "" },
    reportingTime: { type: String, trim: true, maxlength: 180, default: "" },
  },
  startDate: { type: Date, default: null },
  registrationDeadline: { type: Date, default: null },
  timezone: { type: String, trim: true, maxlength: 80, default: "Asia/Kolkata" },
  batches: [{
    code: { type: String, required: true, trim: true, maxlength: 80 },
    label: { type: String, required: true, trim: true, maxlength: 120 },
    deliveryMode: { type: String, enum: ["online", "in-person", "hybrid"], required: true },
    status: { type: String, enum: ["scheduled", "rescheduled", "completed", "cancelled"], default: "scheduled" },
    startsAt: { type: Date, required: true },
    endsAt: { type: Date, default: null },
    timezone: { type: String, required: true, trim: true, maxlength: 80 },
    registrationOpensAt: { type: Date, default: null },
    registrationClosesAt: { type: Date, default: null },
    sessions: [{
      title: { type: String, required: true, trim: true, maxlength: 160 },
      startsAt: { type: Date, required: true },
      endsAt: { type: Date, default: null },
      status: { type: String, enum: ["scheduled", "rescheduled", "completed", "cancelled"], default: "scheduled" },
      onlinePlatform: { type: String, trim: true, maxlength: 80, default: "" },
      onlineJoinUrl: { type: String, trim: true, maxlength: 1000, default: "" },
      onlineAccessCode: { type: String, trim: true, maxlength: 200, default: "" },
      venueName: { type: String, trim: true, maxlength: 180, default: "" },
      venueAddress: { type: String, trim: true, maxlength: 1000, default: "" },
      reportingTime: { type: String, trim: true, maxlength: 180, default: "" },
    }],
  }],
  priceMinor: { type: Number, required: true, min: 0, validate: Number.isSafeInteger },
  listPriceMinor: { type: Number, min: 0, validate: { validator: (value) => value === undefined || value === null || Number.isSafeInteger(value) }, default: null },
  currency: { type: String, enum: ["INR"], default: "INR", required: true },
  internalCostMinor: { type: Number, min: 0, validate: { validator: (value) => value === undefined || value === null || Number.isSafeInteger(value) } },
  enrollmentOpen: { type: Boolean, default: true },
  status: { type: String, enum: ["draft", "scheduled", "published", "unpublished", "archived"], default: "draft", index: true },
  scheduledAt: { type: Date, default: null },
  scheduledBy: { type: mongoose.Schema.Types.ObjectId, ref: "Admin", default: null },
  publishedAt: { type: Date, default: null },
  announcementStatus: { type: String, enum: ["not_eligible", "pending", "queued"], default: "not_eligible", index: true },
  publishedBy: { type: mongoose.Schema.Types.ObjectId, ref: "Admin", default: null },
  scheduleAuditPending: { type: Boolean, default: false, select: false },
  archivedAt: { type: Date, default: null },
  createdBy: { type: mongoose.Schema.Types.ObjectId, ref: "Admin", required: true },
  updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: "Admin", required: true },
}, { timestamps: true, strict: "throw" });

courseSchema.index({ slug: 1 }, { unique: true, name: "course_slug_unique" });
courseSchema.index({ status: 1, scheduledAt: 1 }, { name: "course_schedule_scan" });
courseSchema.index({ status: 1, publishedAt: -1, _id: -1 }, { name: "public_course_catalogue" });
courseSchema.index({ category: 1, status: 1, publishedAt: -1 }, { name: "course_category_public" });

export default mongoose.models.Course || mongoose.model("Course", courseSchema, "courses");
